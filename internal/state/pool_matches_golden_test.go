// TestPoolMatchesGoldenBytes pins the byte-exact file format.
func TestPoolMatchesGoldenBytes(t *testing.T) {
	dir := t.TempDir()
	s, err := NewStore(dir)
	require.NoError(t, err)
	require.NoError(t, s.SaveCompetition(&Competition{ID: "c", Name: "C"}))

	require.NoError(t, s.SavePoolMatches("c", poolMatchesGoldenInput()))
	b, err := os.ReadFile(filepath.Join(dir, "competitions", "c", "pool-matches.csv"))
	require.NoError(t, err)
	assert.Equal(t, poolMatchesGolden, string(b),
		"pool-matches.csv bytes changed; column position is the on-disk contract")
}

// TestPoolMatchesGoldenLoads proves the pinned bytes load back into the same
// results a fresh save would produce, closing the loop from the READ side: a
// reader change that silently reinterprets an existing column fails here even
// if the writer still emits identical bytes.
func TestPoolMatchesGoldenLoads(t *testing.T) {
	dir := t.TempDir()
	s, err := NewStore(dir)
	require.NoError(t, err)
	require.NoError(t, s.SaveCompetition(&Competition{ID: "c", Name: "C"}))
	require.NoError(t, s.atomicWrite(s.compPath("c", "pool-matches.csv"), []byte(poolMatchesGolden), 0600))

	fresh, err := NewStore(dir)
	require.NoError(t, err)
	loaded, err := fresh.LoadPoolMatches("c")
	require.NoError(t, err)
	require.Len(t, loaded, 2)

	want := poolMatchesGoldenInput()
	// Normalise the two encoding-level asymmetries the round trip is allowed:
	// a nil ippon slice loads as the empty slice (splitIppons of ""), and the
	// sub-result's nil IpponsB comes back nil through JSON.
	want[1].IpponsA, want[1].IpponsB = []string{}, []string{}
	assert.Equal(t, want[0], loaded[0])
	assert.Equal(t, want[1], loaded[1])
}
