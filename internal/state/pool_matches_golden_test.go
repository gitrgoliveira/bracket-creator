// hantei, which rides as the mark in the winner's score cell, and an encho,
// which collapses to its period count) and one freshly scheduled with zero
// values everywhere else.
//
// Column position is the on-disk contract (files written by older builds must
// keep loading, and files written now must load in older builds up to their
// column count), so this golden pins the whole format: header wording, column
// order, and every value encoding. It was generated by the writer as it stood
// BEFORE savePoolMatchesLocked/parsePoolMatchesRecords were derived from the
// poolMatchColumns table, so it also proves that refactor changed nothing on
// disk. If this test fails you have changed the file format: that is only
// correct for a NEW APPENDED column, in which case regenerate the tail here
// and say so in the commit.
